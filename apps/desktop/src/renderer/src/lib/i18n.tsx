const dictionaries: Record<Language, Record<TranslationKey, string>> = { es, en };

interface I18nValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children, initialLanguage = 'es' }: { children: ReactNode; initialLanguage?: Language }): React.JSX.Element {
  const [language, setLanguage] = useState<Language>(initialLanguage);

  const t = useCallback(
    (key: TranslationKey, vars?: Record<string, string | number>) => {
      const template = dictionaries[language][key] ?? dictionaries.es[key] ?? key;
      if (!vars) return template;
      return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
    },
    [language],
  );

  const value = useMemo(() => ({ language, setLanguage, t }), [language, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nProvider');
  return value;
}

export function errorKey(code: string): TranslationKey {
  const key = `error.${code}` as TranslationKey;
  return key in es ? key : 'error.INTERNAL';
}
